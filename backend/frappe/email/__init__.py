def make_communication(
    doctype: Optional[str] = None,
    name: Optional[str] = None,
    content: Optional[str] = None,
    subject: Optional[str] = None,
    sent_or_received: str = "Sent",
    sender: Optional[str] = None,
    sender_full_name: Optional[str] = None,
    recipients: Optional[Union[str, list[str]]] = None,
    cc: Optional[str] = None,
    bcc: Optional[str] = None,
    communication_medium: str = "Email",
    send_email: bool = False,
    print_html: Optional[str] = None,
    print_format: Optional[str] = None,
    attachments: Optional[list[dict]] = None,
    ignore_doctype_permissions: bool = False,
    read_receipt: bool = False,
    email_template: Optional[str] = None,
    **kwargs: Any,
) -> "Document":
    """Create a *Communication* document (low-level, internal)."""
    # Normalize recipients to a comma-separated string
    if isinstance(recipients, (list, tuple)):
        recipients = ", ".join(recipients)

    # Resolve sender info
    if not sender:
        sender = _get_default_sender()
    if not sender_full_name:
        try:
            sender_full_name = frappe.utils.get_fullname(
                frappe.session.user if hasattr(frappe.session, "user") else "Administrator"
            )
        except Exception:
            sender_full_name = sender

    data = {
        "doctype": "Communication",
        "subject": subject or "",
        "content": content or "",
        "communication_type": "Communication",
        "communication_medium": communication_medium,
        "sent_or_received": sent_or_received,
        "sender": sender,
        "sender_full_name": sender_full_name,
        "recipients": recipients or "",
        "cc": cc or "",
        "bcc": bcc or "",
        "reference_doctype": doctype,
        "reference_name": name,
        "read_receipt": cint(read_receipt),
        "email_template": email_template,
        "delivery_status": "",
    }

    # Add any extra kwargs that match Communication fields
    for key, value in kwargs.items():
        if key not in data:
            data[key] = value

    doc = frappe.get_doc(data)
    doc.flags.ignore_permissions = ignore_doctype_permissions
    doc.insert(ignore_permissions=ignore_doctype_permissions)

    # Attach files
    if attachments:
        for att in attachments:
            if isinstance(att, dict) and "fname" in att and "fcontent" in att:
                _add_attachment_to_communication(doc, att["fname"], att["fcontent"])

    return doc


