"""
Frappe Email Module

Complete email infrastructure for the Frappe framework replacement:
- Email queue with retry logic and status tracking
- sendmail() API compatible with the original Frappe signature
- SMTP backend abstraction
- Communication logging (every email is a Communication document)
- Contact list / autocomplete helpers
- System manager notification helpers
- Unsubscribe link generation

The module uses ``EmailQueue`` as the core queueing mechanism and
``SMTPConnection`` for actual SMTP delivery.  Both are thin layers
that can be swapped out for external providers (SendGrid, SES, …)
via hooks.

Typical flow::

    # From application code
    frappe.sendmail(
        recipients=["user@example.com"],
        subject="Welcome",
        message="<h1>Hello!</h1>",
        reference_doctype="Sales Order",
        reference_name="SO-00001",
    )

    # Background worker picks up queue and delivers
    from frappe.email import flush
    flush()
"""

