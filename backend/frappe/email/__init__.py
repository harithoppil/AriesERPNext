def get_unsubscribe_message(doctype: str, docname: str) -> str:
    """Return an HTML unsubscribe footer for bulk emails.

    The footer contains a link back to the site with a signed token so
    that the unsubscribe view can verify the request.
    """
    try:
        token = _generate_unsubscribe_token(doctype, docname)
        unsubscribe_url = f"{get_url()}/api/method/frappe.email.unsubscribe?" f"doctype={doctype}&name={docname}&token={token}"

        return (
            '<div style="margin-top: 20px; padding-top: 10px; '
            'border-top: 1px solid #ddd; font-size: 12px; color: #888;">'
            f'<a href="{unsubscribe_url}">Unsubscribe from this list</a>'
            "</div>"
        )
    except Exception:
        return ""


def get_unsubscribed_users(doctype: str, docname: str) -> list[str]:
    """Return the list of email addresses that have unsubscribed from
    notifications for the given document."""
    try:
        return frappe.db.get_all(
            "Email Unsubscribe",
            filters={
                "reference_doctype": doctype,
                "reference_name": docname,
            },
            pluck="email",
        ) or []
    except Exception:
        return []


