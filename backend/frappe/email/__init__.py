def flush() -> dict[str, int]:
    """Deliver all pending emails in the queue.

    This function is invoked by the background job scheduler.  It fetches
    all *Email Queue* documents with status *Not Sent* and attempts to
    deliver them, retrying failed items up to ``config.max_email_retry``
    times (default 3).

    Returns
    -------
    dict :
        ``{"sent": int, "failed": int, "pending": int}``
    """
    max_retries = cint(frappe.conf.get("max_email_retry", 3))
    retry_interval = cint(frappe.conf.get("email_retry_interval", 300))  # 5 min

    pending = _get_pending_queue_items(max_retries, retry_interval)

    stats = {"sent": 0, "failed": 0, "pending": 0}

    for queue_item in pending:
        try:
            queue_item.send()
            stats["sent"] += 1
        except Exception as exc:
            logger.warning(
                "Failed to send email queue %s: %s", queue_item.name, exc,
                exc_info=True,
            )
            queue_item.mark_failed(str(exc))
            stats["failed"] += 1

    stats["pending"] = len(pending) - stats["sent"] - stats["failed"]
    return stats


