def sendmail(
    recipients: Optional[Union[str, list[str]]] = None,
    sender: Optional[str] = None,
    subject: Optional[str] = None,
    message: Optional[str] = None,
    reference_doctype: Optional[str] = None,
    reference_name: Optional[str] = None,
    add_unsubscribe_link: int = 1,
    attachments: Optional[list[dict]] = None,
    reply_to: Optional[str] = None,
    cc: Optional[Union[str, list[str]]] = None,
    bcc: Optional[Union[str, list[str]]] = None,
    print_format: Optional[str] = None,
    send_email: int = 1,
    now: bool = False,
    communication: Optional[str] = None,
    read_receipt: bool = False,
    is_notification: bool = False,
    print_letterhead: bool = True,
    email_template: Optional[str] = None,
    **kwargs: Any,
) -> "EmailQueue":
    """Send an email.

    If *send_email* is 1 (default) the message is added to the email queue
    and will be delivered by a background worker.  If *now* is ``True`` the
    email is sent synchronously in the current process.

    Every outgoing message is also stored as a *Communication* document so
    that the full correspondence history is available from any document.

    Parameters
    ----------
    recipients :
        Primary recipient(s).  String is split on commas.
    sender :
        From address.  Falls back to ``config.mail_login`` or
        ``config.auto_email_id``.
    subject :
        Email subject line.
    message :
        HTML body.  Plain text is auto-generated by stripping HTML.
    reference_doctype / reference_name :
        Link the email to a document for communication history.
    add_unsubscribe_link :
        Append an unsubscribe footer when >0.
    attachments :
        List of ``{"fname": str, "fcontent": bytes}`` dicts.
    reply_to :
        Reply-To header address.
    cc / bcc :
        Carbon-copy / blind carbon-copy addresses.
    print_format :
        Name of a print format to render as PDF attachment.
    send_email :
        0 = create Communication only, do not queue for delivery.
    now :
        Bypass the queue and deliver immediately (synchronous).
    communication :
        Name of an existing Communication document to reuse.
    read_receipt :
        Request a read-receipt (Disposition-Notification-To).
    is_notification :
        Mark the Communication as an automated notification.
    print_letterhead :
        Include the company letterhead when rendering a print format.
    email_template :
        Name of an *Email Template* document to load subject/body from.

    Returns
    -------
    EmailQueue :
        The queue record created for this message.
    """
    if frappe.are_emails_muted():
        logger.info("Emails are muted; skipping sendmail")
        return None  # type: ignore[return-value]

    # ── Resolve recipients ──
    recipient_list = _normalize_address_list(recipients)
    cc_list = _normalize_address_list(cc)
    bcc_list = _normalize_address_list(bcc)

    if not recipient_list and not cc_list and not bcc_list:
        logger.warning("sendmail called with no recipients")
        return None  # type: ignore[return-value]

    # ── Resolve sender ──
    sender = sender or _get_default_sender()

    # ── Load email template if specified ──
    if email_template and not (subject and message):
        subject, message = _load_email_template(email_template, kwargs)

    subject = cstr(subject)
    message = cstr(message)

    # ── Render print format as attachment ──
    if print_format and reference_doctype and reference_name:
        from frappe.printing import get_pdf

        try:
            pdf_data = get_pdf(
                reference_doctype,
                reference_name,
                print_format=print_format,
                letterhead=print_letterhead,
            )
            if pdf_data:
                attachments = attachments or []
                attachments.append(
                    {
                        "fname": f"{reference_name}.pdf",
                        "fcontent": pdf_data,
                    }
                )
        except Exception:
            logger.exception("Failed to generate PDF attachment")

    # ── Create / update Communication ──
    if not communication:
        comm = make_communication(
            doctype=reference_doctype,
            name=reference_name,
            subject=subject,
            content=message,
            sender=sender,
            recipients=", ".join(recipient_list),
            cc=", ".join(cc_list) if cc_list else None,
            bcc=", ".join(bcc_list) if bcc_list else None,
            communication_medium="Email",
            sent_or_received="Sent",
            send_email=bool(send_email),
            read_receipt=read_receipt,
            email_template=email_template,
        )
        communication = comm.name
    else:
        comm = frappe.get_doc("Communication", communication)

    # ── Build unsubscribe link ──
    unsubscribe_msg = ""
    if add_unsubscribe_link and reference_doctype and reference_name:
        unsubscribe_msg = get_unsubscribe_message(reference_doctype, reference_name)
        if unsubscribe_msg and message:
            message = message + "<br><br>" + unsubscribe_msg

    # ── Queue or send immediately ──
    if not send_email:
        return None  # type: ignore[return-value]

    queue_doc = EmailQueue(
        recipients=recipient_list,
        cc=cc_list,
        bcc=bcc_list,
        sender=sender,
        subject=subject,
        message=message,
        attachments=attachments or [],
        reply_to=reply_to,
        reference_doctype=reference_doctype,
        reference_name=reference_name,
        communication=communication,
        read_receipt=read_receipt,
        is_notification=is_notification,
    )

    if now:
        queue_doc.send()
    else:
        queue_doc.add_to_queue()

    return queue_doc


def sendmail_to_system_managers(subject: str, message: str, **kwargs: Any) -> None:
    """Send an email to every user with the *System Manager* role."""
    managers = get_system_managers()
    if not managers:
        logger.warning("No System Managers found; cannot send notification")
        return

    sendmail(
        recipients=managers,
        subject=subject,
        message=message,
        **kwargs,
    )


