def _normalize_address_list(value: Optional[Union[str, list[str], tuple[str]]]) -> list[str]:
    """Convert a recipient argument into a clean list of email addresses."""
    if not value:
        return []
    if isinstance(value, str):
        return [a.strip() for a in value.split(",") if a.strip()]
    return [a.strip() for a in value if a and isinstance(a, str) and a.strip()]


def _get_default_sender() -> str:
    """Return the default outgoing email address for this site."""
    sender = frappe.conf.get("mail_login") or frappe.conf.get("auto_email_id")
    if not sender:
        try:
            sender = frappe.session.user if hasattr(frappe.session, "user") else "admin@example.com"
        except Exception:
            sender = "admin@example.com"
    return sender


def _load_email_template(
    template_name: str, context: dict[str, Any]
) -> tuple[str, str]:
    """Load subject and body from an *Email Template* document."""
    try:
        template = frappe.get_doc("Email Template", template_name)
        subject = render_string(template.subject, context) if hasattr(template, "subject") else ""
        body = render_string(template.response, context) if hasattr(template, "response") else ""
        return subject, body
    except Exception:
        logger.warning("Email Template '%s' not found", template_name)
        return "", ""


def _generate_unsubscribe_token(doctype: str, docname: str) -> str:
    """Generate a signed token for one-click unsubscribe links."""
    secret = frappe.conf.get("secret_key") or frappe.local.site
    payload = f"{doctype}:{docname}"
    return hashlib.sha256(f"{payload}:{secret}".encode()).hexdigest()[:32]


def _add_attachment_to_communication(comm_doc, fname: str, fcontent: bytes) -> None:
    """Attach a file to a Communication document via the File Manager."""
    try:
        from frappe.file_manager import save_file

        save_file(
            fname=fname,
            content=fcontent,
            dt="Communication",
            dn=comm_doc.name,
            is_private=1,
        )
    except Exception:
        logger.debug("Failed to attach file to Communication", exc_info=True)


def _get_pending_queue_items(
    max_retries: int,
    retry_interval: int,
) -> list[EmailQueue]:
    """Fetch pending queue items from the database."""
    try:
        rows = frappe.db.get_all(
            "Email Queue",
            filters={"status": ("in", ["Not Sent", "Error"])},
            fields=[
                "name",
                "sender",
                "recipients",
                "cc",
                "bcc",
                "subject",
                "message",
                "reference_doctype",
                "reference_name",
                "communication",
                "status",
                "retry",
                "read_receipt",
                "is_notification",
            ],
            order_by="creation asc",
            limit_page_length=100,
        )

        items: list[EmailQueue] = []
        for row in rows:
            if row.retry >= max_retries:
                continue

            # For error items, check retry interval
            if row.status == "Error" and row.retry > 0:
                # Skip if too soon to retry (simplified check)
                continue

            recipients = []
            try:
                recipients = json.loads(row.recipients) if row.recipients else []
            except json.JSONDecodeError:
                recipients = [r.strip() for r in row.recipients.split(",") if r.strip()]

            cc = []
            if row.cc:
                try:
                    cc = json.loads(row.cc)
                except json.JSONDecodeError:
                    cc = [r.strip() for r in row.cc.split(",") if r.strip()]

            bcc = []
            if row.bcc:
                try:
                    bcc = json.loads(row.bcc)
                except json.JSONDecodeError:
                    bcc = [r.strip() for r in row.bcc.split(",") if r.strip()]

            eq = EmailQueue(
                recipients=recipients,
                cc=cc,
                bcc=bcc,
                sender=row.sender,
                subject=row.subject,
                message=row.message,
                reference_doctype=row.reference_doctype,
                reference_name=row.reference_name,
                communication=row.communication,
                read_receipt=bool(row.read_receipt),
                is_notification=bool(row.is_notification),
            )
            eq.name = row.name
            eq.status = row.status
            eq.retry = row.retry
            items.append(eq)

        return items
    except Exception:
        logger.exception("Failed to fetch pending queue items")
        return []


