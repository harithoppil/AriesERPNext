#  EMAIL QUEUE  (internal data class)
# ═══════════════════════════════════════════════════════════════════════════════


class EmailQueue:
    """Represents a single email in the queue.

    This class wraps the *Email Queue* DocType and provides a Pythonic
    interface for creating, persisting, and sending queued messages.
    """

    def __init__(
        self,
        recipients: list[str],
        sender: str,
        subject: str,
        message: str,
        cc: Optional[list[str]] = None,
        bcc: Optional[list[str]] = None,
        attachments: Optional[list[dict]] = None,
        reply_to: Optional[str] = None,
        reference_doctype: Optional[str] = None,
        reference_name: Optional[str] = None,
        communication: Optional[str] = None,
        read_receipt: bool = False,
        is_notification: bool = False,
    ):
        self.name: Optional[str] = None
        self.recipients = recipients
        self.cc = cc or []
        self.bcc = bcc or []
        self.sender = sender
        self.subject = subject
        self.message = message
        self.attachments = attachments or []
        self.reply_to = reply_to
        self.reference_doctype = reference_doctype
        self.reference_name = reference_name
        self.communication = communication
        self.read_receipt = read_receipt
        self.is_notification = is_notification
        self.status = "Not Sent"
        self.retry = 0
        self.error = None

    # ── Persistence ──

    def add_to_queue(self) -> None:
        """Create an *Email Queue* document in the database."""
        try:
            doc = frappe.get_doc(
                {
                    "doctype": "Email Queue",
                    "sender": self.sender,
                    "recipients": json.dumps(self.recipients),
                    "cc": json.dumps(self.cc),
                    "bcc": json.dumps(self.bcc),
                    "subject": self.subject,
                    "message": self.message,
                    "reference_doctype": self.reference_doctype,
                    "reference_name": self.reference_name,
                    "communication": self.communication,
                    "status": "Not Sent",
                    "retry": 0,
                    "read_receipt": cint(self.read_receipt),
                    "is_notification": cint(self.is_notification),
                }
            )
            doc.insert(ignore_permissions=True)
            self.name = doc.name

            # Store attachment metadata on the queue doc
            if self.attachments:
                for att in self.attachments:
                    att_doc = frappe.get_doc(
                        {
                            "doctype": "Email Queue Recipient",
                            "parent": doc.name,
                            "parenttype": "Email Queue",
                            "parentfield": "recipients_list",
                            "recipient": att.get("fname", ""),
                            "status": " attachment",
                        }
                    )
                    att_doc.insert(ignore_permissions=True)
        except Exception:
            logger.exception("Failed to add email to queue")

    def send(self) -> None:
        """Deliver the email via SMTP immediately."""
        from frappe.email.smtp import SMTPConnection

        conn = SMTPConnection()

        conn.send_message(
            sender=self.sender,
            recipients=self.recipients,
            subject=self.subject,
            message=self.message,
            cc=self.cc,
            bcc=self.bcc,
            attachments=self.attachments,
            reply_to=self.reply_to,
            read_receipt=self.read_receipt,
        )

        self.status = "Sent"
        self._update_status()

        # Update linked Communication
        if self.communication:
            self._update_communication_status("Delivered")

    def mark_failed(self, error: str) -> None:
        """Mark the queue item as failed and increment retry count."""
        self.retry += 1
        self.error = error
        self.status = "Error"
        self._update_status()

        if self.communication:
            self._update_communication_status("Error")

    def _update_status(self) -> None:
        """Persist status changes back to the database."""
        if self.name:
            try:
                frappe.db.set_value(
                    "Email Queue",
                    self.name,
                    {"status": self.status, "retry": self.retry, "error": self.error},
                )
            except Exception:
                logger.debug("Failed to update queue status for %s", self.name)

    def _update_communication_status(self, delivery_status: str) -> None:
        """Update the linked Communication document delivery status."""
        if self.communication:
            try:
                frappe.db.set_value(
                    "Communication",
                    self.communication,
                    "delivery_status",
                    delivery_status,
                )
            except Exception:
                logger.debug(
                    "Failed to update communication status for %s",
                    self.communication,
                )


