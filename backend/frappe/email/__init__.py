def get_system_managers() -> list[str]:
    """Return a list of email addresses for users with the *System Manager* role.

    Uses the ``Has Role`` and ``User`` DocTypes.  Falls back to the
    ``auto_email_id`` configured for the site if no managers are found.
    """
    try:
        managers = frappe.db.sql(
            """
            SELECT DISTINCT u.email
            FROM `tabUser` u
            INNER JOIN `tabHas Role` hr ON hr.parent = u.name
            WHERE hr.role = 'System Manager'
                AND u.enabled = 1
                AND u.email IS NOT NULL
                AND u.email != ''
            ORDER BY u.email
            """,
            as_dict=False,
        )
        emails = [row[0] for row in managers if row[0] and validate_email_address(row[0])]
        if emails:
            return emails
    except Exception:
        logger.debug("get_system_managers query failed", exc_info=True)

    # Fallback: auto_email_id from config
    auto_email = frappe.conf.get("auto_email_id")
    if auto_email:
        return [auto_email]

    return []


def get_contact_list(doctype: str, fieldname: str, txt: str) -> list[_dict]:
    """Return matching contacts for autocomplete widgets.

    Searches *Contact* documents by first name, last name, or email and
    returns up to 20 matches.
    """
    txt = cstr(txt).strip()
    if not txt:
        return []

    search_pattern = f"%{txt}%"

    try:
        contacts = frappe.db.sql(
            """
            SELECT DISTINCT email_id AS value, full_name AS label
            FROM `tabContact`
            WHERE (
                first_name LIKE %s
                OR last_name LIKE %s
                OR email_id LIKE %s
            )
            AND email_id IS NOT NULL
            AND email_id != ''
            ORDER BY full_name
            LIMIT 20
            """,
            (search_pattern, search_pattern, search_pattern),
            as_dict=True,
        )
        return [_dict(c) for c in contacts if c.get("value")]
    except Exception:
        logger.debug("get_contact_list query failed", exc_info=True)
        return []


def get_communication_doctype(
    doctype: str,
    docname: str,
    limit: int = 50,
) -> list[dict]:
    """Return *Communication* records linked to a document.

    These are shown in the *Communication* timeline on every form.
    """
    try:
        comms = frappe.db.get_all(
            "Communication",
            filters={
                "reference_doctype": doctype,
                "reference_name": docname,
            },
            fields=[
                "name",
                "subject",
                "content",
                "sender",
                "sender_full_name",
                "recipients",
                "cc",
                "communication_medium",
                "sent_or_received",
                "creation",
                "modified",
                "read_receipt",
                "delivery_status",
                "communication_type",
            ],
            order_by="creation desc",
            limit_page_length=limit,
        )
        return comms
    except Exception:
        logger.debug("get_communication_doctype query failed", exc_info=True)
        return []


